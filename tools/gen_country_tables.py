"""Generate the country table for the Kotlin and Swift cores from redtooth/phones.py.

    python tools/gen_country_tables.py kotlin > android/core/src/main/kotlin/app/redtooth/core/Countries.kt
    python tools/gen_country_tables.py swift  > ios/Packages/RedtoothCore/Sources/RedtoothCore/Countries.swift
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from redtooth.phones import COUNTRIES  # noqa: E402


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lang = sys.argv[1] if len(sys.argv) > 1 else "kotlin"
rows = [f"Country({q(c.iso)}, {q(c.name)}, {q(c.cc)}, {q(c.trunk)}, {q(c.idd)})" for c in COUNTRIES]
if lang == "kotlin":
    print("// Generated by tools/gen_country_tables.py from redtooth/phones.py. Do not edit.")
    print("package app.redtooth.core\n")
    print("data class Country(val iso: String, val name: String, val cc: String, val trunk: String = \"0\", val idd: String = \"00\")\n")
    print("val COUNTRIES: List<Country> = listOf(")
    print(",\n".join("    " + r for r in rows))
    print(")")
else:
    print("// Generated by tools/gen_country_tables.py from redtooth/phones.py. Do not edit.")
    print("public struct Country: Hashable, Sendable {")
    print("    public let iso: String, name: String, cc: String, trunk: String, idd: String")
    print("    public init(_ iso: String, _ name: String, _ cc: String, _ trunk: String = \"0\", _ idd: String = \"00\") {")
    print("        self.iso = iso; self.name = name; self.cc = cc; self.trunk = trunk; self.idd = idd")
    print("    }")
    print("}\n")
    print("public let countries: [Country] = [")
    print(",\n".join("    " + r for r in rows))
    print("]")
